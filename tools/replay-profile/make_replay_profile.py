#!/usr/bin/env python3
"""Extracts a replay profile for the simulator from a real TrafficNode export.

Input:  data/traffic_devices_signals.csv (InfluxDB export, columns _time, device_id, voltage_V, current_A, ...)
Output: src/TNWatch.TelemetryIngestion/Simulation/Profiles/<device>.csv with the columns voltage_v,current_a,
        in time order. It is embedded into the TNWatch.TelemetryIngestion assembly, so the Docker build (which only
        copies src/) does not need the data/ folder.

Usage:  python3 tools/replay-profile/make_replay_profile.py [device_id]   (default: TSN-002)
"""
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data" / "traffic_devices_signals.csv"


def main() -> None:
    device = sys.argv[1] if len(sys.argv) > 1 else "TSN-002"
    with SOURCE.open(newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["device_id"] == device]
    rows.sort(key=lambda r: r["_time"])
    if not rows:
        sys.exit(f"No rows for device {device} in {SOURCE}")

    target = ROOT / "src" / "TNWatch.TelemetryIngestion" / "Simulation" / "Profiles" / f"{device.lower()}.csv"
    with target.open("w", newline="") as f:
        f.write(f"# Replay profile of {device}: {rows[0]['_time']} .. {rows[-1]['_time']}, "
                f"{len(rows)} samples (every ~3 min). Generated by tools/replay-profile/make_replay_profile.py\n")
        f.write("voltage_v,current_a\n")
        for r in rows:
            f.write(f"{float(r['voltage_V']):.3f},{float(r['current_A']):.3f}\n")
    print(f"{len(rows)} samples → {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
